package dev.mooner.starlightide.types

import dev.mooner.starlightworkspace.ApiInfo
import dev.mooner.starlightworkspace.EventInfo
import java.lang.reflect.Method
import java.lang.reflect.Modifier

/**
 * TypeScript declarations of what scripts get from StarLight, read from the running app by reflection: the globals of
 * [ApiInfo] and the argument types of [EventInfo], as interfaces in the `StarLight` namespace. The editor loads them so
 * that `Api.` and `/** @param {StarLight.Message} event */` complete.
 *
 * Getters (`getName()`, `isRunning()`) become properties, as script engines expose them. Generics and nullability are
 * erased on the JVM, so collections are `any[]` and nothing is nullable.
 */
class TypeDefinitions(
    /** Finds the classes named by the catalogs, including those of other plugins. */
    private val classLoader: ClassLoader,
) {

    class Result(
        val declarations: String,
        /** TypeScript type of each Java class name the declarations cover, such as `StarLight.Message`. */
        val typeNames: Map<String, String>,
    ) {
        fun typeOf(className: String): String =
            typeNames[className] ?: "any"
    }

    fun generate(apis: List<ApiInfo>, events: List<EventInfo>): Result {
        val generator = Generator()
        val globals = apis.mapNotNull { api ->
            val type = generator.typeOf(api.instanceClass)
            "/** ${api.instanceType.lowercase()} ${api.instanceClass} */\ndeclare const ${identifier(api.name) ?: return@mapNotNull null}: $type;"
        }
        events.forEach { event -> event.args.forEach { generator.typeOf(it.type) } }
        generator.drain()

        val declarations = buildString {
            appendLine("// StarLight's script API, generated by the IDE from the running app.")
            appendLine("declare namespace $NAMESPACE {")
            for (body in generator.interfaces.values)
                appendLine(body.prependIndent("    "))
            appendLine("}")
            globals.forEach(::appendLine)
        }
        return Result(declarations, generator.names.mapValues { (_, name) -> "$NAMESPACE.$name" })
    }

    private inner class Generator {

        /** Java class name to the interface name in the namespace. */
        val names: MutableMap<String, String> = linkedMapOf()
        val interfaces: MutableMap<String, String> = linkedMapOf()
        private val queue = ArrayDeque<Class<*>>()

        fun typeOf(className: String): String {
            val cls = load(className) ?: return "any"
            return typeOf(cls)
        }

        fun drain() {
            while (queue.isNotEmpty() && interfaces.size < MAX_INTERFACES) {
                val cls = queue.removeFirst()
                interfaces[cls.name] = declare(cls)
            }
        }

        private fun typeOf(cls: Class<*>): String =
            when {
                cls == Void.TYPE || cls == Void::class.java || cls.name == "kotlin.Unit" -> "void"
                cls == String::class.java || CharSequence::class.java.isAssignableFrom(cls) || cls == Char::class.javaPrimitiveType || cls == Character::class.java -> "string"
                cls == Boolean::class.javaPrimitiveType || cls == java.lang.Boolean::class.java -> "boolean"
                cls.isPrimitive || Number::class.java.isAssignableFrom(cls) -> "number"
                cls.isArray -> "${typeOf(cls.componentType!!).let { if (it.contains(' ')) "($it)" else it }}[]"
                Iterable::class.java.isAssignableFrom(cls) -> "any[]"
                Map::class.java.isAssignableFrom(cls) -> "Record<string, any>"
                cls.name.startsWith("kotlin.jvm.functions.") -> "(...args: any[]) => any"
                cls.name.startsWith(OWN_PACKAGES) && !cls.isEnum && !cls.isAnonymousClass -> "$NAMESPACE.${nameOf(cls)}"
                else -> "any"
            }

        private fun nameOf(cls: Class<*>): String {
            names[cls.name]?.let { return it }
            val base = cls.simpleName.ifEmpty { "Anonymous" }
            var name = base
            var suffix = 2
            while (name in names.values)
                name = base + suffix++
            names[cls.name] = name
            queue += cls
            return name
        }

        private fun declare(cls: Class<*>): String {
            val name = names.getValue(cls.name)
            val properties = linkedMapOf<String, String>()
            val methods = arrayListOf<String>()
            for (method in members(cls)) {
                val property = propertyName(method)
                if (property != null) {
                    properties.putIfAbsent(property, typeOf(method.returnType))
                    continue
                }
                val params = method.parameterTypes.mapIndexed { i, type -> "p$i: ${typeOf(type)}" }.joinToString()
                methods += "${method.name}($params): ${typeOf(method.returnType)};"
            }
            return buildString {
                appendLine("/** ${cls.name} */")
                appendLine("interface $name {")
                for ((property, type) in properties)
                    appendLine("    readonly $property: $type;")
                for (method in methods.distinct())
                    appendLine("    $method")
                append("}")
            }
        }

        private fun members(cls: Class<*>): List<Method> =
            runCatching { cls.methods.toList() }.getOrDefault(emptyList())
                .filter { method ->
                    Modifier.isPublic(method.modifiers) && !Modifier.isStatic(method.modifiers) &&
                        !method.isSynthetic && !method.isBridge && method.declaringClass != Any::class.java &&
                        identifier(method.name) != null && method.name !in HIDDEN_METHODS && !COMPONENT.matches(method.name)
                }
                .sortedBy(Method::getName)

        private fun load(className: String): Class<*>? =
            runCatching { Class.forName(className, false, classLoader) }.getOrNull()
    }

    private companion object {
        const val NAMESPACE = "StarLight"
        const val MAX_INTERFACES = 80

        /** Types worth describing; others are `any`. */
        const val OWN_PACKAGES = "dev.mooner."

        val HIDDEN_METHODS = setOf("equals", "hashCode", "toString", "copy", "getClass", "wait", "notify", "notifyAll")
        val COMPONENT = Regex("component\\d+")
        val IDENTIFIER = Regex("[A-Za-z_$][A-Za-z0-9_$]*")

        fun identifier(name: String): String? =
            name.takeIf { IDENTIFIER.matches(it) && '$' !in it }

        /** `getName()` and `isRunning()` as `name` and `running`. */
        fun propertyName(method: Method): String? {
            if (method.parameterCount != 0 || method.returnType == Void.TYPE)
                return null
            val name = method.name
            val rest = when {
                name.startsWith("get") && name.length > 3 && name[3].isUpperCase() -> name.substring(3)
                name.startsWith("is") && name.length > 2 && name[2].isUpperCase() -> name.substring(2)
                else -> return null
            }
            return rest.replaceFirstChar(Char::lowercaseChar)
        }
    }
}
